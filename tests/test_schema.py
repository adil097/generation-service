async def test_attempt_linkage_and_active_uniqueness(app_connection, task):
    await rejected(
        app_connection,
        sa.insert(GenerationAttempt).values(attempt_values(task, provider_name="beta")),
        "23503",
    )
    values = attempt_values(task)
    await app_connection.execute(sa.insert(GenerationAttempt).values(values))
    second = attempt_values(
        task, leg_id=task["legs"][1].id, provider_name="beta", attempt_number=2
    )
    await rejected(app_connection, sa.insert(GenerationAttempt).values(second), "23505")
    await app_connection.execute(
        sa.update(GenerationAttempt)
        .where(GenerationAttempt.id == values["id"])
        .values(
            status="failed",
            error_type="technical",
            finished_at=datetime.now(timezone.utc),
        )
    )
    await app_connection.execute(sa.insert(GenerationAttempt).values(second))
    # A finalized attempt remains unique per leg and per attempt number.
    await rejected(
        app_connection,
        sa.insert(GenerationAttempt).values(attempt_values(task, attempt_number=3)),
        "23505",
    )


