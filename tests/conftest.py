import asyncio
import os
from uuid import uuid4

import sqlalchemy as sa
from sqlalchemy.engine import make_url
from sqlalchemy.ext.asyncio import create_async_engine

import pytest


@pytest.fixture
def settings_values() -> dict[str, str]:
    return {
        "database_url": "postgresql+asyncpg://test:test@localhost:5432/test",
        "alpha_webhook_secret": "alpha-test-secret",
        "beta_webhook_secret": "beta-test-secret",
        "payments_webhook_secret": "payments-test-secret",
    }


@pytest.fixture(scope="session")
def database_factory():
    keys = {
        "admin": "TEST_ADMIN_DATABASE_URL",
        "migration": "TEST_MIGRATION_DATABASE_URL",
        "app": "TEST_DATABASE_URL",
        "provider": "TEST_PROVIDER_DATABASE_URL",
    }
    if not all(os.environ.get(key) for key in keys.values()):
        pytest.skip("Run the Compose test service to test schema and role permissions")
    urls = {role: os.environ[key] for role, key in keys.items()}
    names = []

    async def execute_admin(statement):
        engine = create_async_engine(urls["admin"], isolation_level="AUTOCOMMIT")
        try:
            async with engine.connect() as connection:
                await connection.execute(sa.text(statement))
        finally:
            await engine.dispose()

    def create():
        name = "test_schema_" + uuid4().hex
        asyncio.run(
            execute_admin(f'CREATE DATABASE "{name}" OWNER generation_migrator')
        )
        names.append(name)
        return {
            role: make_url(url).set(database=name).render_as_string(hide_password=False)
            for role, url in urls.items()
        }

    yield create
    for name in names:
        # Only databases generated by this fixture are removed; never the service database.
        assert name.startswith("test_schema_") and len(name) == 44
        asyncio.run(execute_admin(f'DROP DATABASE "{name}" WITH (FORCE)'))
